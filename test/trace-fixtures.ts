/**
 * Synthetic Claude Code transcript lines, shaped like the real JSONL (the
 * keys, flags and wrappers Claude Code writes) with made-up repos, prompts and
 * output. Shared by the trace tests; not a test file itself.
 */
let n = 0;
const uuid = () => `00000000-0000-4000-8000-${String(++n).padStart(12, "0")}`;
const SESSION = "5f0c1a2b-3c4d-4e5f-8a9b-0c1d2e3f4a5b";

function base(extra: Record<string, unknown> = {}) {
  return {
    parentUuid: null,
    isSidechain: false,
    userType: "external",
    cwd: "/home/dev/shop",
    sessionId: SESSION,
    version: "2.1.29",
    gitBranch: "main",
    entrypoint: "cli",
    uuid: uuid(),
    timestamp: "2026-10-01T10:00:00.000Z",
    ...extra,
  };
}

/** A prompt the person typed, as newer builds stamp it. */
export const typed = (content: unknown, extra: Record<string, unknown> = {}) =>
  base({ type: "user", message: { role: "user", content }, origin: { kind: "human" }, promptId: uuid(), permissionMode: "default", ...extra });

/** A prompt from a build that predates `origin`. */
export const typedOld = (content: unknown, extra: Record<string, unknown> = {}) => base({ type: "user", message: { role: "user", content }, ...extra });

