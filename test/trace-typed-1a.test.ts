test("classifyAnswer: an adversarial table of replies to an offer", () => {
  assert.ok(REPLIES.length >= 100, `${REPLIES.length} replies`);
  const wrong: string[] = [];
  for (const [t, want] of REPLIES) {
    for (const afterShow of [false, true]) {
      const got = classifyAnswer(t, afterShow);
      const ok = want === "!yes" ? got !== "yes" : want === "show" && afterShow ? got === "other" : got === want;
      if (!ok) wrong.push(`${JSON.stringify(t.slice(0, 50))} (afterShow ${afterShow}): ${got}, want ${want}`);
    }
  }
  assert.deepEqual(wrong, []);
});

test("classifyAnswer: show me once, then it is other", () => {
  for (const t of ["show me", "show", "show me the steps", "show it", "show me the draft", "show me first please", "let me see", "let me see it", "what are the steps", "see the steps", "what's in it", "whats in it"]) {
    assert.equal(classifyAnswer(t, false), "show", t);
    assert.equal(classifyAnswer(t, true), "other", t);
  }
});

