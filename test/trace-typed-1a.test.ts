/**
 * Phase 1a's readers of what the person typed: a save request, the scope
 * words in it, the answer to an offer (a closed list of whole-message forms:
 * "ok now fix the lint errors" is not a yes), a correction, and the one form
 * typed text is ever stored in, its hash.
 *
 * (`test/trace-typed.test.ts` is phase 0's, for whose words a transcript line holds.)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { ownText } from "../src/trace/claude.js";
import { NOT_SAVE, SAVE_REQUEST, classifyAnswer, isCorrection, isSaveRequest, scopeWords, typedPrompt, typedSha } from "../src/trace/typed.js";

test("typedPrompt is phase 0's ownText, null when that is empty", () => {
  const cases = [
    "publish 1.4.3",
    '<ide_opened_file>The user opened /home/dev/shop/a.ts</ide_opened_file>\nwhy is the total negative',
    "<task-notification>done</task-notification>",
    "Caveat: the messages below were generated by the user while running local commands.",
    "<system-reminder>x</system-reminder>",
    "   ",
    '<pasted_content id="1">a long log</pasted_content id="1">',
    'look at this <pasted_content id="1">log</pasted_content id="1">',
  ];
  for (const raw of cases) assert.equal(typedPrompt(raw), ownText(raw) || null, raw);
  assert.equal(typedPrompt("publish 1.4.3"), "publish 1.4.3");
  assert.equal(typedPrompt("<task-notification>done</task-notification>"), null);
});

test("save requests: the spec's phrasings", () => {
  for (const t of [
    "save this as a skill", "can you keep what you just did as a skill?", "make a skill out of that", "save these steps for next time",
    "Save this as a skill please", "turn that into a skill", "keep it as a skill", "make this into a skill", "save the steps as a skill",
    "remember how you did this", "remember how to do that", "make a skill from this", "keep that for next time", "ok great, save what you did as a skill for the team",
  ]) {
    assert.equal(isSaveRequest(t), true, t);
    assert.match(t, SAVE_REQUEST);
  }
});

test("near misses are not save requests", () => {
  for (const t of [
    "save this file", "don't save this as a skill", "save it to disk", "keep this as a note", "do not make that a skill", "never keep this as a skill",
    "no need to save this as a skill", "save the skill file I wrote", "what is a skill", "remember to run the tests",
  ]) assert.equal(isSaveRequest(t), false, t);
  assert.match("don't save this as a skill", NOT_SAVE);
  // Over 25 words, it is a task that mentions skills.
  assert.equal(isSaveRequest(`save this as a skill ${"and then also do this other thing ".repeat(4)}`), false);
  // Inside pasted code or a quoted line, it is not the person asking.
  assert.equal(isSaveRequest("what does this do\n```\nsave this as a skill\n```"), false);
  assert.equal(isSaveRequest("> save this as a skill\nwhy does it say that"), false);
});

