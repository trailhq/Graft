test("classifyAnswer: a correction, otherwise other", () => {
  for (const t of ["no, use the ssh remote", "that's wrong, push to beta first", "actually, run the tests first", "you keep pushing to prod first", "i told you to use ssh"]) {
    assert.equal(classifyAnswer(t, false), "correction", t);
  }
  assert.equal(classifyAnswer("ff to prod now", false), "other");
});

test("isCorrection (ported)", () => {
  assert.equal(isCorrection("no, I meant the other file"), true);
  assert.equal(isCorrection("stop doing that"), true);
  assert.equal(isCorrection("it should be beta not prod"), true);
  assert.equal(isCorrection("you did it again?"), true);
  assert.equal(isCorrection("push to beta"), false);
  assert.equal(isCorrection(`no, ${"x".repeat(400)}`), false, "a task, not a correction");
});

test("typedSha: sha256 hex of the NFC text, trimmed, spaces collapsed", () => {
  const a = typedSha("yes  please");
  assert.match(a, /^[0-9a-f]{64}$/);
  assert.equal(typedSha(" yes please\n"), a);
  assert.equal(typedSha("yes\tplease"), a);
  assert.notEqual(typedSha("Yes please"), a);
  assert.equal(typedSha("café"), typedSha("café"));
  assert.equal(a, createHash("sha256").update("yes please").digest("hex"));
});
