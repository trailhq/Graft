/**
 * Generate the Hermes plugin for team knowledge injection.
 *
 * Creates ~/.hermes/plugins/trail-knowledge/ with:
 *   - plugin.yaml  — manifest
 *   - __init__.py  — setup(ctx) registering pre_llm_call; injects knowledge on first turn only
 *
 * Also enables the plugin in config.yaml (plugins.enabled list).
 *
 * Why pre_llm_call (not pre_api_request):
 *   - pre_api_request return value is IGNORED by the conversation loop
 *   - pre_llm_call {"context":"..."} IS consumed by _collect_pre_llm_call_context()
 *     and injected into the user message. Receives is_first_turn to fire ONCE per session.
 *
 * Source verified in:
 *   hermes-agent/agent/turn_context.py:_collect_pre_llm_call_context()
 *   hermes-agent/agent/shell_hooks.py:_parse_pre_llm_call()
 *   hermes-agent/hermes_cli/plugins_discovery.py (plugins.enabled opt-in)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';

const PLUGIN_NAME = 'trail-knowledge';

const PLUGIN_YAML = `\
name: trail-knowledge
label: Trail Team Knowledge
kind: agent
version: 1.0.0
author: trail-code-detacoop
description: >
  Inject team knowledge (global policies, app-specific docs) at the start of
  each session. Reads from the knowledge repo configured in ~/.trail/config.json.
  Fires only on the first LLM call of each session (is_first_turn=True).
  Auto-generated by trail init.
requires_hermes: ">=0.10.0"
provides_hooks:
  - pre_llm_call
requires_env: []
`;

const PLUGIN_PY = `\
"""
Trail team knowledge plugin for Hermes.

Injects global policies, app-specific docs, agent instructions, and always-follow
learnings (guardrails) from the current repo at the start of each session.

Event: pre_llm_call — fires before every LLM call; is_first_turn=True only on
the first call of each session. Context returned as {"context": "..."} is
injected into the user message by _collect_pre_llm_call_context().

Auto-generated by trail init — re-run trail init to update.
"""
from __future__ import annotations

import json
import logging
import os
import re
from pathlib import Path

logger = logging.getLogger(__name__)

_INJECTED: set[str] = set()


def _trail_home() -> Path:
    env = os.environ.get("TRAIL_HOME")
    return Path(env) if env else Path.home() / ".trail"


def _knowledge_repo_dir() -> Path | None:
    config_path = _trail_home() / "config.json"
    if not config_path.exists():
        return None
    try:
        cfg = json.loads(config_path.read_text(encoding="utf-8"))
        url: str = cfg.get("knowledgeRepo", "")
        if not url:
            return None
        name = url.rstrip("/").rstrip(".git").rsplit("/", 1)[-1]
        if not name:
            return None
    except Exception:
        return None
    try:
        cwd = Path.cwd()
    except OSError:
        return None
    for candidate in [cwd, *cwd.parents]:
        dest = candidate / name
        if (dest / ".git").exists():
            return dest
    return None


def _read_md_files(directory: Path) -> list[str]:
    if not directory.is_dir():
        return []
    results = []
    for f in sorted(directory.glob("*.md")):
        if f.name.lower() == "readme.md":
            continue
        try:
            content = f.read_text(encoding="utf-8").strip()
            if content:
                results.append(content)
        except Exception:
            pass
    return results


def _is_guardrail(text: str) -> bool:
    \"\"\"Return True when the frontmatter declares kind: guardrail or standing: true.\"\"\"
    if not text.startswith("---"):
        return False
    end = text.find("\\n---", 3)
    if end == -1:
        return False
    fm = text[3:end]
    if re.search(r"^kind:\\s*guardrail", fm, re.MULTILINE):
        return True
    if re.search(r"^standing:\\s*true", fm, re.MULTILINE):
        return True
    return False


def _strip_frontmatter(text: str) -> str:
    \"\"\"Remove the YAML frontmatter block, return the body.\"\"\"
    if not text.startswith("---"):
        return text
    end = text.find("\\n---", 3)
    if end == -1:
        return text
    body = text[end + 4:].lstrip("\\n")
    return body


def _read_guardrails(repo_dir: Path) -> list[str]:
    \"\"\"Read always-follow learnings (guardrails) from .trail/learnings/.\"\"\"
    learnings_dir = repo_dir / ".trail" / "learnings"
    if not learnings_dir.is_dir():
        return []
    results = []
    for f in sorted(learnings_dir.glob("*.md")):
        try:
            text = f.read_text(encoding="utf-8").strip()
            if not text or not _is_guardrail(text):
                continue
            body = _strip_frontmatter(text).strip()
            # Extract title from frontmatter for the header
            title_m = re.search(r"^title:\\s*(.+)$", text[:text.find("\\n---", 3) if text.startswith("---") else 0], re.MULTILINE)
            title = title_m.group(1).strip().strip('"') if title_m else f.stem
            results.append(f"**[Always follow]** {title}\\n\\n{body}")
        except Exception:
            pass
    return results


def _build_knowledge_context(knowledge_dir: Path) -> str | None:
    parts: list[str] = []
    parts.extend(_read_md_files(knowledge_dir / "knowledge" / "global"))
    workflow_md = knowledge_dir / "knowledge" / "agents" / "hermes" / "WORKFLOW.md"
    if workflow_md.exists():
        try:
            content = workflow_md.read_text(encoding="utf-8").strip()
            if content:
                parts.append(content)
        except Exception:
            pass
    try:
        app_name = Path.cwd().name
    except OSError:
        app_name = ""
    if app_name:
        parts.extend(_read_md_files(knowledge_dir / "knowledge" / "apps" / app_name))
    if not parts:
        return None
    separator = "\\n\\n---\\n\\n"
    return "## \\U0001f4da Team Knowledge\\n\\n" + separator.join(parts)


def setup(ctx) -> None:
    def inject_knowledge(
        is_first_turn: bool = False,
        session_id: str = "",
        **_kwargs,
    ) -> dict | None:
        if not is_first_turn:
            return None
        if session_id and session_id in _INJECTED:
            return None

        parts: list[str] = []

        # Always-follow guardrails from the current git repo
        try:
            cwd = Path.cwd()
            for candidate in [cwd, *cwd.parents]:
                if (candidate / ".git").exists():
                    guardrails = _read_guardrails(candidate)
                    if guardrails:
                        separator = "\\n\\n---\\n\\n"
                        parts.append(
                            "## \\u26a0\\ufe0f Always-Follow Rules\\n\\n"
                            "These rules hold regardless of what you are asked to do. "
                            "Do not go against them; if a request conflicts, stop and name the rule.\\n\\n"
                            + separator.join(guardrails)
                        )
                    break
        except Exception:
            pass

        # Team knowledge repo (global policies, app docs)
        knowledge_dir = _knowledge_repo_dir()
        if knowledge_dir:
            context = _build_knowledge_context(knowledge_dir)
            if context:
                parts.append(context)

        if not parts:
            return None

        context = "\\n\\n".join(parts)
        if session_id:
            _INJECTED.add(session_id)
        logger.debug("trail-knowledge: injecting context (%d chars)", len(context))
        return {"context": context}

    ctx.register_hook("pre_llm_call", inject_knowledge)
`;

function hermesHome(home: string = homedir()): string {
  const local = process.env.LOCALAPPDATA;
  if (process.platform === 'win32' && local) return join(local, 'hermes');
  return join(home, '.hermes');
}

function enablePluginInConfig(configPath: string, pluginName: string): void {
  if (!existsSync(configPath)) return;
  let text: string;
  try { text = readFileSync(configPath, 'utf8'); } catch { return; }
  if (text.includes(`- ${pluginName}`)) return;

  // Find `enabled:` then scan lines until we hit the first `- ` item to detect indentation,
  // skipping blank lines. Insert the new entry before the first existing item.
  const enabledIdx = text.search(/^\s+enabled:\s*$/m);
  if (enabledIdx !== -1) {
    const afterEnabled = text.indexOf('\n', enabledIdx) + 1;
    // Find the first `- ` item line after `enabled:` (may be separated by blank lines).
    const firstItemMatch = /^([ \t]+)- /m.exec(text.slice(afterEnabled));
    if (firstItemMatch) {
      const indent = firstItemMatch[1];
      const insertAt = afterEnabled + (firstItemMatch.index ?? 0);
      text = text.slice(0, insertAt) + `${indent}- ${pluginName}\n` + text.slice(insertAt);
    } else {
      // `enabled:` exists but has no items yet — append with 4-space indent.
      text = text.slice(0, afterEnabled) + `    - ${pluginName}\n` + text.slice(afterEnabled);
    }
  } else {
    // No `plugins: enabled:` block at all — append at end.
    text += `\nplugins:\n  enabled:\n    - ${pluginName}\n`;
  }
  try { writeFileSync(configPath, text, 'utf8'); } catch { /* best-effort */ }
}

export function writeHermesKnowledgeHook(home: string = homedir()): boolean {
  const hHome = hermesHome(home);
  if (!existsSync(hHome)) return false;
  const pluginDir = join(hHome, 'plugins', PLUGIN_NAME);
  mkdirSync(pluginDir, { recursive: true });
  writeFileSync(join(pluginDir, 'plugin.yaml'), PLUGIN_YAML, 'utf8');
  writeFileSync(join(pluginDir, '__init__.py'), PLUGIN_PY, 'utf8');
  const configPath = join(hHome, 'config.yaml');
  enablePluginInConfig(configPath, PLUGIN_NAME);
  return true;
}
