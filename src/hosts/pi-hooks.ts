/**
 * Pi's active-layer install. Pi has no `hooks.json` — it loads in-process
 * extensions — so the four hook events arrive as extension events instead of
 * host config entries. Two files, mirroring the Codex install:
 *
 *   - the SAME shim Codex uses (`~/.pi/hooks/graft/graft-hooks.cjs`): the real
 *     hook logic stays in the package (`hooks.js`'s `main(event)`) and upgrades
 *     with it, behind the same stdin/stdout contract and the same test seams;
 *   - a tiny generated adapter (`~/.pi/agent/extensions/graft-hooks.ts`) that
 *     spawns that shim on each event and reshapes the result for pi.
 *
 * The adapter spawns a subprocess per event, exactly as Codex's hooks.json
 * entries do — same cost, same timeouts, and a wedged child becomes a no-op
 * rather than a hung session.
 *
 * User-level (`~/.pi`), so `--no-global` suppresses these and the picker labels
 * them machine-wide, like the Codex hook targets. `piHookTargets()` is the pure
 * half (planning / retract); `installPiHooks()` does the writes.
 */
import { rmSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { hooksShim } from '../claude/shim-template.js';
import type { PlannedWrite } from './plan.js';
import { writeOwned, type ConfigWrite } from './config-write.js';
import type { Brand } from '../brand.js';

function dirExists(p: string): boolean {
  try { return statSync(p).isDirectory(); } catch { return false; }
}

/** `~/.pi/hooks/graft/graft-hooks.cjs`, or trail's names in a trail repo. */
export function piShimPathFor(home: string, name: Brand = 'graft'): string {
  return join(home, '.pi', 'hooks', name, `${name}-hooks.cjs`);
}

/** `~/.pi/agent/extensions/graft-hooks.ts` — pi's user-level extension dir. */
export function piExtensionPathFor(home: string, name: Brand = 'graft'): string {
  return join(home, '.pi', 'agent', 'extensions', `${name}-hooks.ts`);
}

/**
 * The files a Pi-hooks install would touch — pure, no writes. Both live under
 * `~/.pi`, so both are scoped 'global': the extension fires in every repo opened
 * with Pi, not just this one. Empty when Pi isn't installed (no `~/.pi`),
 * mirroring `installCodexHooks`' early return on a missing `~/.codex`.
 */
export function piHookTargets(home: string, name: Brand = 'graft'): PlannedWrite[] {
  if (!dirExists(join(home, '.pi'))) return [];
  return [
    {
      hostId: 'pi', id: 'pi-hook-shim',
      path: piShimPathFor(home, name),
      scope: 'global', kind: 'hook', what: 'post-edit hook shim',
    },
    {
      hostId: 'pi', id: 'pi-hooks',
      path: piExtensionPathFor(home, name),
      scope: 'global', kind: 'hook', what: 'session_start / before_agent_start / tool_result / agent_end',
    },
  ];
}

/**
 * The generated Pi extension: the translation layer between pi's event API and
 * the shim's stdin/stdout contract. Each handler spawns
 * `node <shim> <sub-command>` with the Claude-Code-shaped payload the package
 * already understands (so every handler in `hooks.js` runs unchanged) and
 * reshapes the printed `additionalContext` into pi's result shapes:
 *
 *   - `session_start` → the `session-start` sub (orientation + housekeeping);
 *     its context is stashed, because session_start itself cannot inject —
 *     pi's injection point is `before_agent_start` (see the docs' events table).
 *   - `before_agent_start` → the `prompt` sub (the retrieval pack, the accuracy
 *     hook), plus the stashed orientation the first time this session, delivered
 *     as one custom message. Custom messages become user messages for the model
 *     (`convertToLlm`), so this is UserPromptSubmit parity.
 *   - `tool_result` on edit/write → the `post-edit` sub (blast radius + dirty),
 *     appended to the tool result the model reads. PostToolUse parity.
 *   - `agent_end` → the `stop` sub (one background graph sync at turn end).
 *     Stop parity; the sub spawns a detached child, so this returns at once.
 *
 * Timeouts mirror the Codex entries (15s for the prompt, 10s elsewhere): on
 * timeout or a missing shim the event resolves empty and the session carries
 * on — hooks are enhancements, never load-bearing.
 */
export function piExtensionTemplate(shimPath: string, name: Brand = 'graft'): string {
  const fn = `${name}PiHooks`;
  return `// Generated by \`graft init\` (pi hook adapter) — do not edit; re-running init rewrites it.
// Spawns the hooks shim on pi's four hook events and reshapes the results.
// The real logic lives in the installed package's hooks.js and upgrades with it.
import { spawn } from "node:child_process";
import { isAbsolute, resolve } from "node:path";

const SHIM = ${JSON.stringify(shimPath)};
const TIMEOUT_MS: Record<string, number> = { prompt: 15000, "session-start": 10000, "post-edit": 10000, stop: 10000 };

/** Spawn the shim with the payload on stdin; resolve the additionalContext it
 * printed, or null. A missing shim, a wedged child or unparseable output all
 * resolve null — the event becomes a clean no-op. */
function runHook(sub: string, payload: Record<string, unknown>): Promise<string | null> {
  return new Promise((resolveHook) => {
    let child;
    try {
      child = spawn(process.execPath, [SHIM, sub], { stdio: ["pipe", "pipe", "ignore"] });
    } catch {
      resolveHook(null);
      return;
    }
    let out = "";
    const done = (value: string | null) => { clearTimeout(timer); resolveHook(value); };
    const timer = setTimeout(() => { child.kill(); done(null); }, TIMEOUT_MS[sub] ?? 10000);
    child.stdout.on("data", (chunk) => { out += chunk; });
    child.on("error", () => done(null));
    child.on("close", () => {
      try {
        const context = JSON.parse(out)?.hookSpecificOutput?.additionalContext;
        done(typeof context === "string" && context ? context : null);
      } catch { done(null); }
    });
    child.stdin.on("error", () => { /* shim exited before reading stdin */ });
    child.stdin.end(JSON.stringify(payload));
  });
}

export default function ${fn}(pi: any): void {
  let sessionId = "default";
  let orientation: string | null = null;
  let orientationDelivered = false;

  pi.on("session_start", async (_event: any, ctx: any) => {
    try { sessionId = ctx.sessionManager.getSessionId(); } catch { /* pre-session start */ }
    orientation = await runHook("session-start", { cwd: ctx.cwd, session_id: sessionId });
    orientationDelivered = false;
  });

  pi.on("before_agent_start", async (event: any, ctx: any) => {
    const parts: string[] = [];
    if (!orientationDelivered && orientation) { parts.push(orientation); orientationDelivered = true; }
    const prompt = typeof event?.prompt === "string" ? event.prompt : "";
    const pack = await runHook("prompt", { prompt, cwd: ctx.cwd, session_id: sessionId });
    if (pack) parts.push(pack);
    if (!parts.length) return;
    return { message: { customType: "${name}-context", content: parts.join("\\n\\n"), display: false } };
  });

  pi.on("tool_result", async (event: any, ctx: any) => {
    if (event?.isError) return;
    if (event?.toolName !== "edit" && event?.toolName !== "write") return;
    const filePath = event?.input?.path;
    if (typeof filePath !== "string" || !filePath) return;
    // The package's edit handling reads absolute paths (Claude Code's shape).
    const absolute = isAbsolute(filePath) ? filePath : resolve(ctx.cwd, filePath);
    const blast = await runHook("post-edit", { tool_input: { file_path: absolute }, cwd: ctx.cwd, session_id: sessionId });
    if (!blast) return;
    return { content: [...(event.content ?? []), { type: "text", text: blast }] };
  });

  // Fire-and-forget: the stop sub spawns the graph sync detached and returns.
  pi.on("agent_end", (_event: any, ctx: any) => {
    void runHook("stop", { cwd: ctx.cwd, session_id: sessionId });
  });
}
`;
}

/**
 * Install (or refresh) Pi's hook layer. Idempotent: the shim and the adapter
 * are both graft-owned files, rewritten only when their content changed. Under
 * trail, graft's adapter goes so pi never loads both (the stale adapter would
 * keep firing graft's shim); the shim itself is inert without an adapter.
 */
export function installPiHooks(home: string, name: Brand = 'graft'): ConfigWrite[] {
  const targets = piHookTargets(home, name);
  if (targets.length === 0) return [];
  const shimWrite = writeOwned('pi-hook-shim', targets[0].path, hooksShim(), 0o755);
  if (name === 'trail') {
    rmSync(piExtensionPathFor(home, 'graft'), { force: true });
    rmSync(piShimPathFor(home, 'graft'), { force: true });
  }
  const extWrite = writeOwned('pi-hooks', targets[1].path, piExtensionTemplate(targets[0].path, name));
  return [shimWrite, extWrite];
}
